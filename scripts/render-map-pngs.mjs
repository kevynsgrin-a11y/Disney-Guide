/**
 * Rasterises the map plates to PNG.
 *
 * Deliberately NOT part of `npm run build`. The site itself has no dependencies and must stay that
 * way; rasterising needs a browser engine, which is a heavy thing to put in a CI build that
 * currently installs nothing. So the PNGs are generated here, committed, and copied to dist/ by the
 * build like any other asset.
 *
 * That trades a dependency for a staleness risk, so the audit checks the PNGs against the mtimes of
 * the data and styling they came from and complains when they fall behind.
 *
 * Requires playwright-core and a Chromium build:
 *   npm i -D playwright-core        (or rely on PLAYWRIGHT_BROWSERS_PATH in this environment)
 *   npm run maps:png
 */

import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'dist', 'maps')
const OUT = join(ROOT, 'assets', 'img', 'maps')

/* Two widths: one for sharing and one that still holds up printed at A4. */
const WIDTHS = [{ suffix: '', width: 1600 }, { suffix: '@2x', width: 3200 }]

async function findChromium () {
  const base = process.env.PLAYWRIGHT_BROWSERS_PATH || '/opt/pw-browsers'
  if (!existsSync(base)) return null
  const dir = (await readdir(base)).find((d) => d.startsWith('chromium-'))
  if (!dir) return null
  const exe = join(base, dir, 'chrome-linux', 'chrome')
  return existsSync(exe) ? exe : null
}

async function main () {
  if (!existsSync(SRC)) {
    console.error('\n  dist/maps/ does not exist. Run `npm run build` first.\n')
    process.exit(1)
  }

  let chromium
  try {
    ({ chromium } = await import('playwright-core'))
  } catch {
    console.log('\n  playwright-core is not installed — skipping PNG generation.')
    console.log('  The SVG plates in dist/maps/ are unaffected; PNGs are a convenience format.\n')
    return
  }

  const executablePath = await findChromium()
  const browser = await chromium.launch(
    executablePath ? { executablePath, args: ['--no-sandbox'] } : { args: ['--no-sandbox'] }
  )

  await mkdir(OUT, { recursive: true })
  const files = (await readdir(SRC)).filter((f) => f.endsWith('.svg'))
  let written = 0

  for (const file of files) {
    const svg = await readFile(join(SRC, file), 'utf8')
    const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1]
    if (!viewBox) { console.warn(`  skipped ${file} — no viewBox`); continue }
    const [, , vw, vh] = viewBox.split(/\s+/).map(Number)
    const ratio = vh / vw

    for (const { suffix, width } of WIDTHS) {
      const height = Math.round(width * ratio)
      const page = await browser.newPage({ viewport: { width, height } })
      // A data URL keeps this a pure rasterisation with no server and no network.
      await page.setContent(
        `<!doctype html><meta charset="utf-8">
         <style>html,body{margin:0;padding:0;background:#f2e6cd}svg{display:block;width:100vw;height:auto}</style>
         ${svg.replace(/^<\?xml[^>]*\?>\s*/, '')}`,
        { waitUntil: 'load' }
      )
      await page.waitForTimeout(180) // let the turbulence filters settle
      const name = file.replace(/\.svg$/, `${suffix}.png`)
      await page.screenshot({ path: join(OUT, name), clip: { x: 0, y: 0, width, height } })
      await page.close()
      written++
    }
    console.log(`  ${file} → ${WIDTHS.length} PNG${WIDTHS.length === 1 ? '' : 's'}`)
  }

  await browser.close()

  // Stamp the source of truth so the audit can detect drift.
  await writeFile(
    join(OUT, 'GENERATED.json'),
    JSON.stringify({
      note: 'Generated by scripts/render-map-pngs.mjs. Re-run `npm run maps:png` after changing any map.json or src/lib/map-style.mjs.',
      files: files.length,
      images: written,
    }, null, 2) + '\n',
    'utf8'
  )

  console.log(`\n  Wrote ${written} PNG plates to assets/img/maps/\n`)
}

main().catch((err) => { console.error(err); process.exit(1) })
